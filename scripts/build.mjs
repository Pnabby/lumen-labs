import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const files = { 'index.html': 'text/html; charset=utf-8', 'styles.css': 'text/css; charset=utf-8', 'app.js': 'text/javascript; charset=utf-8', 'image.png': 'image/png', 'assets/favicon.svg': 'image/svg+xml' };
const assets = {};
for (const [file, type] of Object.entries(files)) { const data = await readFile(path.join(root, file)); const encoding = file.endsWith('.png') ? 'base64' : 'utf8'; assets['/' + file] = { type, encoding, body: data.toString(encoding) }; }
const handler = (await readFile(path.join(root, 'worker/handler.mjs'), 'utf8')).replace(/^export /gm, '');
const output = `// Generated by scripts/build.mjs. Edit source files instead.\nconst assets = ${JSON.stringify(assets)};\n${handler}\nexport default makeWorker(assets);\n`;
await mkdir(path.join(root, 'dist/server'), { recursive: true });
await mkdir(path.join(root, 'dist/.openai'), { recursive: true });
await writeFile(path.join(root, 'dist/server/index.js'), output);
await writeFile(path.join(root, 'dist/.openai/hosting.json'), await readFile(path.join(root, '.openai/hosting.json')));
console.log(`Built Lumen Labs: ${Object.keys(assets).length} assets, ${Buffer.byteLength(output).toLocaleString()} byte Worker.`);
